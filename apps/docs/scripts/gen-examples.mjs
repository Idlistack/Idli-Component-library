// Regenerates examples/index.ts from the files in examples/<component>/<name>.tsx.
// Run with `npm run gen:examples -w docs` after adding an example.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../examples/", import.meta.url));
const ids = [];
for (const dir of readdirSync(root).sort()) {
  if (!statSync(join(root, dir)).isDirectory()) continue;
  for (const file of readdirSync(join(root, dir)).sort()) ids.push(`${dir}/${file.replace(/\.tsx$/, "")}`);
}

const pascal = (s) => s.split(/[/-]/).map((w) => w[0].toUpperCase() + w.slice(1)).join("");
let out = '// Generated by scripts/gen-examples.mjs — maps example ids to their components.\nimport type { ComponentType } from "react";\n';
for (const id of ids) out += `import ${pascal(id)} from "./${id}";\n`;
out += "\nexport const examples: Record<string, ComponentType> = {\n" + ids.map((id) => `  "${id}": ${pascal(id)},`).join("\n") + "\n};\n";
writeFileSync(join(root, "index.ts"), out);
console.log(`Wrote ${ids.length} examples`);
